"""Survival acquisition implemented in native entity/block interactions.

Only runtime spawn/feature data and existing handlers are represented here.
Probabilities, encounter difficulty and specific enchantment components are
documented rather than simulated by this qualitative item reachability graph.
"""
import json


JAVA = 'src/main/java/io/github/jimbozoomer/jugcraft/'


def extend(root, edge, evidence, items):
    res = root / 'src/main/resources'

    def read(path):
        return json.loads(path.read_text(encoding='utf-8'))

    def found(item, source, note):
        if item in items:
            evidence[item].append({'kind': 'native_acquisition', 'source': JAVA + source, 'note': note})

    aquatic = read(res / 'jugcraft/newest_aquatic.json')
    species = {row['name']: row for row in aquatic['fish']}
    # Registration alone is not a source: only species with an actual native
    # spawn entry may be captured. In particular, a missing species stays missing.
    for entry in aquatic['spawns']:
        name = entry['spawn']['type'].removeprefix('jugcraft:aquatic_')
        if name in species and entry['spawn']['weight'] > 0:
            edge(JAVA + 'aquatic/OwnerAquaculture.java', 'water_bucket_capture_of_naturally_spawned_' + name,
                 ['minecraft:water_bucket'], ['jugcraft:aquatic_' + name + '_bucket'])

    # OwnerFilletRecipe accepts exactly one supported fish and one native Knife;
    # vanilla fish have explicit yields and imported species provide theirs.
    fish = ['minecraft:cod', 'minecraft:salmon', 'minecraft:pufferfish']
    fish += ['jugcraft:aquatic_' + name for name, row in species.items() if row['fillets'] > 0]
    knives = ['jugcraft:aquatic_' + material + '_fillet_knife'
              for material in ('wooden', 'stone', 'iron', 'gold', 'diamond', 'neptunium')]
    edge(JAVA + 'aquatic/OwnerFilletRecipe.java', 'native_one_fish_one_knife_crafting',
         [fish, knives], ['jugcraft:aquatic_fish_fillet_raw'])
    # Wheat seeds carry vanilla's compostable component. This records one real
    # renewable input, not an invented conversion from finished bone meal.
    edge(JAVA + 'aquatic/OwnerWormFarm.java', 'compost_then_harvest_worm_farm',
         ['jugcraft:aquatic_worm_farm', 'minecraft:wheat_seeds'], ['jugcraft:aquatic_worm'])

    twigs_source = JAVA + 'building/OwnerTwigsWorld.java'
    edge(twigs_source, 'native_gravel_bonus_loot', ['minecraft:gravel'], ['jugcraft:twigworks_pebble'])
    edge(twigs_source, 'native_leaf_stick_drop_replacement', ['#minecraft:leaves'], ['jugcraft:twigworks_twig'])
    edge(twigs_source, 'native_leafy_bamboo_bonus_loot', ['minecraft:bamboo'], ['jugcraft:twigworks_bamboo_leaves'])
    # Follow the actual registered placed-feature chain. Merely having a feature
    # file on disk does not make it part of any biome's generation.
    for addition in read(res / 'jugcraft/newest_twigs_biomes.json'):
        additions = addition['features']
        for placed in additions if isinstance(additions, list) else [additions]:
            ns, name = placed.split(':', 1)
            definition = read(res / 'data' / ns / 'worldgen/placed_feature' / (name + '.json'))
            configured = definition['feature']
            if not isinstance(configured, str):
                continue
            ns, name = configured.split(':', 1)
            feature = read(res / 'data' / ns / 'worldgen/feature' / (name + '.json'))
            if feature.get('type') == 'jugcraft:twigworks_natural' and feature.get('kind') == 'patch_seashell':
                for color in ('opaline', 'tangerine', 'roseate', 'bronzed'):
                    found('jugcraft:twigworks_' + color + '_seashell', 'building/OwnerTwigsWorld.java',
                          'The registered ' + placed + ' biome feature places this seashell; its native block loot retains the item.')

    edge(JAVA + 'wilds/WildGroveTrades.java', 'grove_merchant_gold_nugget_trade',
         ['minecraft:gold_nugget'], ['jugcraft:wilds_clawed_log'])
    edge(JAVA + 'wilds/WildGrottol.java', 'silk_touch_capture_of_naturally_spawned_grottol',
         ['#minecraft:pickaxes', 'minecraft:enchanted_book'], ['jugcraft:wilds_captured_grottol'])
    for phase in ('full', 'gibbous', 'half', 'crescent', 'new'):
        found('jugcraft:wilds_elokosa_paw_' + phase, 'wilds/WildElokosa.java',
              'Naturally spawned jungle Elokosa have a chance to drop this paw on death at the corresponding moon phase; daytime yields New Moon.')
    found('jugcraft:wilds_ice_crystal', 'wilds/WildFrostmaw.java',
          'A Frostmaw generated by WildFrostSite drops its crystal when killed by a player while still carrying it; invisible players can instead steal it while it sleeps.')
    found('jugcraft:wilds_music_disc_petiole', 'wilds/WildFrostmaw.java',
          'After its crystal has been taken, a Frostmaw killed by a player while it rains drops this record.')

    edge(JAVA + 'ribbits/Ribbit.java', 'ribbit_merchant_maraca_trade',
         ['minecraft:amethyst_shard'], ['jugcraft:ribbits_maraca'])
    edge(JAVA + 'menagerie/OwnerAmendmentCauldrons.java', 'dye_water_in_cauldron_then_bottle',
         ['minecraft:cauldron', 'minecraft:water_bucket', 'minecraft:white_dye', 'minecraft:glass_bottle'],
         ['jugcraft:amends_dye_bottle'])

    # These are usable world states, not obtainable item stacks: actual block
    # loot deliberately returns their base material even with Silk Touch.
    exclusions = {
        'jugcraft:wilds_grant_suns_blessing': 'Creative administrator item: OwnerWilds registers an unlimited permanent Blessing grant. Survival players earn the effect through the Umvuthi encounter instead of receiving this control item.',
        'jugcraft:aquatic_farmland': 'In-world soil state: OwnerNeptunium.SeaHoe tills dirt into moist farmland; its native block loot returns dirt, not a farmland item.',
        'jugcraft:wilds_raked_sand': 'In-world sand state: WildRakedSand.Rake converts sand; its native block loot returns ordinary sand, not a raked-sand item.',
        'jugcraft:wilds_red_raked_sand': 'In-world sand state: WildRakedSand.Rake converts red sand; its native block loot returns ordinary red sand, not a raked-sand item.',
        'jugcraft:jugtania_solid_vine': 'In-world vine state placed by BotanicalThrownTools vine-ball impacts; its native loot delegates to minecraft:blocks/vine and cannot yield the registered solid-vine item.',
    }
    return {item: reason for item, reason in exclusions.items() if item in items}
